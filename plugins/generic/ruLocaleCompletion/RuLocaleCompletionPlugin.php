 * @brief Fills the gaps of the OJS 3.5 translations (keys shown as
 *  ##locale.key## in the interface): Russian strings are translated in
 *  locale/ru/locale.po; for every other interface language the missing
 *  strings fall back to English (fallback/, generated on deployment).
 *  No settings; always active once installed.
 */

namespace APP\plugins\generic\ruLocaleCompletion;

use PKP\facades\Locale;
use PKP\plugins\GenericPlugin;

class RuLocaleCompletionPlugin extends GenericPlugin
{
    /**
     * Besides its own Russian translations, register the English fallback
     * strings generated by scripts/lib/build-locale-fallback.php (fallback/
     * <locale>/fallback.po) so that untranslated keys of any interface
     * language show English text instead of ##key##.
     *
     * @param null|mixed $mainContextId
     */
    public function register($category, $path, $mainContextId = null)
    {
        $success = parent::register($category, $path, $mainContextId);
        $fallback = $this->getPluginPath() . '/fallback';
        if ($success && is_dir($fallback)) {
            Locale::registerPath($fallback, 1);
        }
        return $success;
    }

    public function isSitePlugin()
    {
        return true;
    }

    public function getEnabled($contextId = null)
    {
        return true;
    }

    public function getCanEnable()
    {
        return false;
    }

    public function getCanDisable()
    {
        return false;
    }

    public function getDisplayName()
    {
        return __('plugins.generic.ruLocaleCompletion.displayName');
    }

    public function getDescription()
    {
        return __('plugins.generic.ruLocaleCompletion.description');
    }
}
